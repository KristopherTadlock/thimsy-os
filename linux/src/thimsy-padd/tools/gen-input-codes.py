"""Writes src/core/InputCodes.inc from the kernel's uapi input-event-codes.h.

    gen-input-codes.py [HEADER] > src/core/InputCodes.inc

HEADER defaults to /usr/include/linux/input-event-codes.h. The table maps the names that
device.json and the replay traces use (EV_, SYN_, KEY_ and BTN_, ABS_, MSC_, SW_) to their
numbers. Aliases (BTN_A for BTN_SOUTH, KEY_SCREENLOCK for KEY_COFFEE) are kept for reading;
the canonical name of a number, used for printing, is the last plain number defined for it
(BTN_SOUTH, not BTN_GAMEPAD). *_MAX and *_CNT are left out. The names and numbers are the
kernel's user-space interface; the header is GPL-2.0 WITH Linux-syscall-note.

Runs on Python 3.8 and later, stdlib only.
"""
from __future__ import annotations

import re
import sys

GROUPS = [
    ("kEvCodes", ("EV_",)),
    ("kSynCodes", ("SYN_",)),
    ("kKeyCodes", ("KEY_", "BTN_")),
    ("kAbsCodes", ("ABS_",)),
    ("kMscCodes", ("MSC_",)),
    ("kSwCodes", ("SW_",)),
]

DEFINE = re.compile(r"^#define\s+([A-Z][A-Z0-9_]*)\s+([^\s/]+)")


def group_of(name: str):
    for gname, prefixes in GROUPS:
        if name.startswith(prefixes):
            return gname
    return None


def parse(text: str):
    values = {}  # name -> int
    entries = {g: [] for g, _ in GROUPS}  # group -> [(name, value, numeric)]
    for line in text.splitlines():
        m = DEFINE.match(line)
        if not m:
            continue
        name, rhs = m.group(1), m.group(2)
        if name.endswith("_MAX") or name.endswith("_CNT"):
            continue
        g = group_of(name)
        if g is None:
            continue
        if re.fullmatch(r"0x[0-9a-fA-F]+|[0-9]+", rhs):
            value = int(rhs, 0)
            numeric = True
        elif rhs in values:
            value = values[rhs]
            numeric = False
        else:
            continue
        values[name] = value
        entries[g].append((name, value, numeric))
    return entries


def render(entries) -> str:
    out = [
        "// Generated by tools/gen-input-codes.py from linux/input-event-codes.h; do not edit.",
        "// Columns: name, number, canonical (the name printed for the number).",
    ]
    for gname, _ in GROUPS:
        rows = entries[gname]
        canonical = {}
        for name, value, numeric in rows:
            if numeric:
                canonical[value] = name
        out.append("static const CodeName %s[] = {" % gname)
        for name, value, _numeric in rows:
            out.append('    {"%s", 0x%03x, %s},' % (name, value,
                                                    "true" if canonical.get(value) == name else "false"))
        out.append("};")
    return "\n".join(out) + "\n"


def main(argv) -> int:
    path = argv[1] if len(argv) > 1 else "/usr/include/linux/input-event-codes.h"
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        text = f.read()
    sys.stdout.write(render(parse(text)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
