#!/usr/bin/env python3
"""Writes NanoEsdeEmulators.inc, ES-DE's emulators per system, for Nano.

  gen_esde_emulators.py ES_SYSTEMS_XML ES_FIND_RULES_XML > NanoEsdeEmulators.inc

Both files are ES-DE's resources/systems/android ones. Each command keeps its
label and its text (a RetroArch command in ES-DE's usual form as @ra:<core>),
with the keys Nano matches its own emulators by: core:<name> for a RetroArch
core, pkg:<package> for each Android package of the emulator it starts.
"""

import re
import sys
import xml.etree.ElementTree as ET

COMMIT = "50e4b600ae533d772bae3ff880d11a09b05dbe84"
RA_TEMPLATE = ("%EMULATOR_RETROARCH% %EXTRA_CONFIGFILE%=%EXTERNALDATA%/Android/data/%ANDROIDPACKAGE%/files/"
               "retroarch.cfg %EXTRA_LIBRETRO%=%INTERNALDATA%/%ANDROIDPACKAGE%/cores/{}_libretro_android.so "
               "%EXTRA_ROM%=%ROM%")
CORE_RE = re.compile(r"/cores/([^/\s]+?)_libretro(?:_android)?\.so")
EMULATOR_RE = re.compile(r"%EMULATOR_([^%]+)%")


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def packages(find_rules):
    out = {}
    for e in ET.parse(find_rules).getroot().findall("emulator"):
        pkgs = []
        for rule in e.findall("rule"):
            if rule.get("type") != "androidpackage":
                continue
            for entry in rule.findall("entry"):
                pkg = (entry.text or "").strip().split("/")[0]
                if pkg and pkg not in pkgs:
                    pkgs.append(pkg)
        out[e.get("name")] = pkgs
    return out


def main(systems_xml, find_rules):
    pkgs = packages(find_rules)
    systems, commands = [], []
    for s in ET.parse(systems_xml).getroot().findall("system"):
        name = s.findtext("name").strip()
        systems.append((name, s.findtext("extension").strip(), (s.findtext("platform") or "").strip(),
                        (s.findtext("theme") or "").strip()))
        for c in s.findall("command"):
            text = " ".join(c.text.split())
            label = c.get("label") or ""
            core = CORE_RE.search(text)
            if core:
                keys = ["core:" + core.group(1)]
                if text == RA_TEMPLATE.format(core.group(1)):
                    text = "@ra:" + core.group(1)
            else:   # an app; RetroArch without a core Nano can name matches nothing
                emu = EMULATOR_RE.match(text)
                keys = ["pkg:" + p for p in pkgs.get(emu.group(1), [])] if emu and emu.group(1) != "RETROARCH" else []
            commands.append((name, label, text, " ".join(keys)))
    print("// ES-DE's emulators per system, from ES-DE's resources/systems/android/es_systems.xml and")
    print(f"// es_find_rules.xml at {COMMIT[:9]}. Generated by tools/gen_esde_emulators.py: do not hand-edit.")
    print("// A system's commands are in es_systems.xml order (the first is ES-DE's default). command @ra:<core>")
    print("// is RetroArch with that core in ES-DE's usual form; keys: core:<name>, pkg:<package> (space separated).")
    print("struct EsdeCommandRow { const char* system; const char* label; const char* command; const char* keys; };")
    print("static const EsdeCommandRow kEsdeCommands[] = {")
    for row in commands:
        print("    {" + ", ".join(c_str(v) for v in row) + "},")
    print("};")
    print("struct EsdeSystemRow { const char* system; const char* extension; const char* platform; const char* theme; };")
    print("static const EsdeSystemRow kEsdeSystemDefs[] = {")
    for row in systems:
        print("    {" + ", ".join(c_str(v) for v in row) + "},")
    print("};")
    print("static const char kEsdeRetroArchCommand[] =")
    print("    " + c_str(RA_TEMPLATE.replace("{}", "{core}")) + ";")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
