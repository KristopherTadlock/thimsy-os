"""Writes the GL stub's generic part (docs/linux/IMPLEMENTATION.md C.1, D.3; README.md here).

Every GL and EGL function the link leaves undefined, minus the ones the hand-written glue defines,
gets a generic stub (glstub.h's GLSTUB_GENERIC_GL / _EGL). The names come from nm, so the list
follows Nano's code with nothing committed:

  gen.py --out glstub_gen.c --objects a.o b.o libx.a --defined-objects glue.o
  gen.py --out glstub_gen.c --undefined nm-u.txt --defined nm-defined.txt

--objects and --defined-objects run `nm -P` (NM from the environment, default nm) on the files;
--undefined and --defined read saved nm output in BSD or POSIX format. Standard library only,
Python 3.8 or later.
"""
from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from typing import Iterable, List, Set, Tuple

GL_NAME = re.compile(r"^(?:gl|egl)[A-Z0-9][A-Za-z0-9_]*$")
# nm's symbol types that define a symbol (upper case: global).
DEFINED_TYPES = set("TDBRWVGSAiCu")


def parse_nm(text: str) -> Tuple[Set[str], Set[str]]:
    """(undefined, defined) global symbol names in nm output, BSD (`addr T name`, `U name`) or POSIX
    (`name T addr size`, `name U`) format. File headers (`x.o:`) and blank lines are skipped."""
    undefined: Set[str] = set()
    defined: Set[str] = set()
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.endswith(":"):
            continue
        parts = line.split()
        name = typ = None
        if len(parts) >= 2 and len(parts[1]) == 1 and parts[1].isalpha() and not _is_hex(parts[0]):
            name, typ = parts[0], parts[1]          # POSIX: name type [value [size]]
        elif len(parts) == 2 and len(parts[0]) == 1:
            typ, name = parts[0], parts[1]          # BSD, undefined: type name
        elif len(parts) == 3 and len(parts[1]) == 1:
            typ, name = parts[1], parts[2]          # BSD: value type name
        if name is None or typ is None:
            continue
        name = name.split("@", 1)[0]
        if typ == "U":
            undefined.add(name)
        elif typ in DEFINED_TYPES:
            defined.add(name)
    return undefined, defined


def _is_hex(s: str) -> bool:
    return bool(s) and all(c in "0123456789abcdefABCDEF" for c in s)


def gl_names(names: Iterable[str]) -> List[str]:
    return sorted(n for n in set(names) if GL_NAME.match(n))


def generate(undefined: Iterable[str], defined: Iterable[str]) -> str:
    """The C source for every GL/EGL name in UNDEFINED that DEFINED does not hold."""
    have = set(defined)
    names = [n for n in gl_names(undefined) if n not in have]
    out = [
        "/* Generated by nano/test/host/glstub/gen.py from the link's undefined GL and EGL symbols.",
        " * Do not edit; nothing here is committed. %d generic stubs. */" % len(names),
        '#include "glstub.h"',
        "",
    ]
    for n in names:
        out.append("GLSTUB_GENERIC_%s(%s)" % ("EGL" if n.startswith("egl") else "GL", n))
    out.append("")
    out.append("const char* const glstub_generic_names[] = {")
    for n in names:
        out.append('    "%s",' % n)
    out.append("    0,")
    out.append("};")
    out.append("const unsigned glstub_generic_count = %du;" % len(names))
    out.append("")
    return "\n".join(out)


def run_nm(files: List[str], undefined_only: bool) -> str:
    if not files:
        return ""
    nm = os.environ.get("NM", "nm")
    cmd = [nm, "-P", "-g"] + (["-u"] if undefined_only else ["--defined-only"]) + files
    proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if proc.returncode != 0:
        raise SystemExit("gen.py: %s failed: %s" % (" ".join(cmd), proc.stderr.decode("utf-8", "replace")))
    return proc.stdout.decode("utf-8", "replace")


def main(argv: List[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", required=True, help="the C file to write")
    ap.add_argument("--objects", nargs="*", default=[], help="objects and archives whose undefined symbols count")
    ap.add_argument("--defined-objects", nargs="*", default=[], help="objects whose definitions are excluded")
    ap.add_argument("--undefined", action="append", default=[], help="saved nm output: its U symbols count")
    ap.add_argument("--defined", action="append", default=[], help="saved nm output: its definitions are excluded")
    args = ap.parse_args(argv)

    undefined: Set[str] = set()
    defined: Set[str] = set()
    for path in args.undefined:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            undefined |= parse_nm(f.read())[0]
    for path in args.defined:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            defined |= parse_nm(f.read())[1]
    undefined |= parse_nm(run_nm(args.objects, True))[0]
    # An object can define what another needs (two objects of the link): those are not stubbed either.
    defined |= parse_nm(run_nm(args.objects, False))[1] if args.objects else set()
    defined |= parse_nm(run_nm(args.defined_objects, False))[1]

    text = generate(undefined, defined)
    tmp = args.out + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    os.replace(tmp, args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
